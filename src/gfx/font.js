export const GLYPH_W = 5;
export const GLYPH_H = 7;
const SPACING = 1;

const cache = new Map();

function bake(color) {
  const chars = Object.keys(GLYPHS);
  const canvas = document.createElement('canvas');
  canvas.width = chars.length * GLYPH_W;
  canvas.height = GLYPH_H;
  const c = canvas.getContext('2d');
  c.fillStyle = color;
  chars.forEach((ch, index) => {
    const rows = GLYPHS[ch].split('/');
    for (let y = 0; y < rows.length; y++) {
      for (let x = 0; x < rows[y].length; x++) {
        if (rows[y][x] === '#') c.fillRect(index * GLYPH_W + x, y, 1, 1);
      }
    }
  });
  const map = new Map();
  chars.forEach((ch, index) => map.set(ch, index * GLYPH_W));
  const sheet = { canvas, map };
  cache.set(color, sheet);
  return sheet;
}

export function textWidth(text, scale = 1) {
  return (text.length * (GLYPH_W + SPACING) - SPACING) * scale;
}

/**
 * Draws pixel text. `align` is 'left' | 'center' | 'right'.
 * `scale` must be a whole number to keep the pixels square.
 */
export function drawText(ctx, text, x, y, {
  color = '#ffffff', align = 'left', shadow = null, scale = 1,
} = {}) {
  const str = String(text).toUpperCase();
  let ox = Math.round(x);
  if (align === 'center') ox = Math.round(x - textWidth(str, scale) / 2);
  else if (align === 'right') ox = Math.round(x - textWidth(str, scale));

  if (shadow) {
    drawText(ctx, str, ox + scale, y + scale, { color: shadow, align: 'left', scale });
  }

  const sheet = cache.get(color) || bake(color);
  const oy = Math.round(y);
  let cx = ox;
  for (const ch of str) {
    const sx = sheet.map.get(ch);
    if (sx !== undefined) {
      ctx.drawImage(sheet.canvas, sx, 0, GLYPH_W, GLYPH_H,
        cx, oy, GLYPH_W * scale, GLYPH_H * scale);
    }
    cx += (GLYPH_W + SPACING) * scale;
  }
  return cx - SPACING * scale - ox;
}
